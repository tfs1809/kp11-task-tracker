def connection(*, migrator=False):
    return psycopg.connect(
        dbname=os.environ["POSTGRES_DB"],
        user=os.environ["DB_MIGRATOR_USER"] if migrator else os.environ["DB_APP_USER"],
        password=os.environ["DB_MIGRATOR_PASSWORD"] if migrator else os.environ["DB_APP_PASSWORD"],
        host=os.environ.get("DB_HOST", "localhost"),
        port=os.environ.get("DB_PORT", "5432"),
        row_factory=dict_row,
    )


@contextmanager
def transaction():
    with connection() as conn:
        with conn.transaction():
            yield conn


def ensure_runtime_schema():
    with connection(migrator=True) as conn:
        with conn.transaction():
            for statement in SCHEMA_STATEMENTS:
                conn.execute(statement)
            conn.execute("INSERT INTO access_accessguard(id) VALUES (1) ON CONFLICT (id) DO NOTHING")
            for code, name, admin_only in PERMISSIONS:
                conn.execute("INSERT INTO access_permission(code,name,admin_only) VALUES (%s,%s,%s) ON CONFLICT (code) DO NOTHING", (code, name, admin_only))
            roles = (
                ("administrator", "Администратор", True),
                ("curator", "Куратор", False),
                ("manager", "Руководитель", False),
                ("teacher", "Преподаватель", False),
            )
            for key, name, system_admin in roles:
                role = one(conn, "SELECT id FROM access_role WHERE key=%s", (key,))
                if not role:
                    import uuid
                    role_id = uuid.uuid4()
                    conn.execute("INSERT INTO access_role(id,key,name,is_active,is_system_admin,version) VALUES (%s,%s,%s,true,%s,1)", (role_id, key, name, system_admin))
                else:
                    role_id = role["id"]
                if system_admin:
                    for code, _, _ in PERMISSIONS:
                        conn.execute("INSERT INTO access_rolepermission(permission_id,role_id) VALUES (%s,%s) ON CONFLICT DO NOTHING", (code, role_id))
            conn.execute("GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA public TO kp11_app")
            conn.execute("GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO kp11_app")


def one(conn, query, params=()):
    return conn.execute(query, params).fetchone()


def many(conn, query, params=()):
    return conn.execute(query, params).fetchall()
